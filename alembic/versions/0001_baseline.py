# calculate_job_relevance is called by every /jobs/search query.
FUNCTIONS_SQL = r"""
CREATE OR REPLACE FUNCTION public.calculate_job_relevance(
    text_score double precision, quality_score numeric,
    posted_date timestamp without time zone, salary_disclosed boolean)
RETURNS double precision LANGUAGE plpgsql STABLE AS $function$
DECLARE
    days_old DOUBLE PRECISION;
    freshness DOUBLE PRECISION;
BEGIN
    days_old := GREATEST(0, EXTRACT(EPOCH FROM (NOW() - posted_date)) / 86400.0);
    freshness := GREATEST(0, 1 - (days_old / 90.0));
    RETURN
        0.4 * LEAST(COALESCE(text_score, 0), 1.0) +
        0.3 * (COALESCE(quality_score, 0) / 100.0) +
        0.2 * freshness +
        0.1 * (CASE WHEN salary_disclosed THEN 1.0 ELSE 0.0 END);
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS trigger LANGUAGE plpgsql AS $function$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_company_job_count()
RETURNS trigger LANGUAGE plpgsql AS $function$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE companies
        SET active_jobs_count = active_jobs_count + 1,
            total_jobs_posted = total_jobs_posted + 1,
            last_job_posted_at = NEW.posted_date
        WHERE id = NEW.company_id;
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.status = 'active' AND NEW.status != 'active' THEN
            UPDATE companies SET active_jobs_count = active_jobs_count - 1 WHERE id = NEW.company_id;
        ELSIF OLD.status != 'active' AND NEW.status = 'active' THEN
            UPDATE companies SET active_jobs_count = active_jobs_count + 1 WHERE id = NEW.company_id;
        END IF;
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        IF OLD.status = 'active' THEN
            UPDATE companies SET active_jobs_count = active_jobs_count - 1 WHERE id = OLD.company_id;
        END IF;
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$function$;
"""

